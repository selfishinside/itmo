alive(Person, Year) :- born(Person, BYear), Year >= BYear, (died(Person, DYear) -> Year < DYear ; true).

spouses(P1, P2, Year) :- married(P1, P2, MYear), Year >= MYear, (divorced(P1, P2, DYear) -> Year < DYear ; true).

children(Parent, Child) :- parent(Parent, Child).

parents(Child, Parent) :- parent(Parent, Child).

siblings(A, X) :-
    setof(B, P^(parent(P, A), parent(P, B), A \= B), X).


grandparent(GP, GC) :- parent(GP, P), parent(P, GC).

grandchild(GC, GP) :- grandparent(GP, GC).

ancestor(A, X) :- parent(A, X).
ancestor(A, X) :- parent(A, Y), ancestor(Y, X).

descendant(D, X) :- parent(X, D).
descendant(D, X) :- parent(X, Y), descendant(D, Y).

married_in_year(P, Y) :- spouses(P, _, Y).

divorced_in_year(P, Y) :- divorced(P, _, DY), Y >= DY.

widowed(P, Y) :- spouses(P, M, SY), died(M, DY), Y >= DY.

brother(A, B) :- sibling(A, B), male(A).

sister(A, B) :- sibling(A, B), female(A).

uncle_or_aunt(UA, X) :- parent(P, X), sibling(UA, P).

nephew_or_niece(N, UA) :- uncle_or_aunt(UA, N).

greatgrandparent(GGP, GC) :- parent(GGP, P), grandparent(P, GC).

greatgrandchild(GC, GGP) :- greatgrandparent(GGP, GC).

