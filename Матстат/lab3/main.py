import numpy as np
from scipy.stats import chi2

# === Шаг 0. Исходные данные ===
lambda_ = 1.76  # параметр экспоненциального распределения
alpha = 0.05    # уровень значимости
num_bins = 10   # количество интервалов
x = np.array([
    0.47, 0.44, 0.3, 0.23, 0.19, 0.84, 0.05, 0.18, 0.58, 1.0, 0.86, 2.88, 0.19, 0.07, 0.15,
    0.18, 2.45, 0.03, 0.57, 0.2, 0.11, 0.26, 0.33, 0.07, 0.27, 0.07, 0.09, 0.77, 0.82, 0.21,
    0.05, 0.2, 0.43, 0.22, 0.09, 1.63, 0.82, 0.4, 0.24, 0.26, 1.54, 0.36, 0.4, 0.18, 0.01, 0.04,
    0.29, 0.07, 0.37, 0.04, 1.39, 0.32, 0.24, 0.56, 1.02, 0.1, 0.0, 0.97, 0.16, 0.06, 0.22, 0.65,
    0.11, 0.04, 1.39, 0.17, 0.51, 0.38, 0.24, 0.02, 0.06, 0.01, 1.94, 1.38, 1.0, 1.42, 0.12, 2.46,
    0.76, 0.01, 1.0, 0.66, 0.95, 0.18, 0.04, 0.8, 0.06, 1.04, 0.37, 0.02, 0.21, 0.72, 0.34, 0.09,
    0.48, 0.36, 0.89, 0.33, 0.25, 1.13
])
n = len(x)  # объём выборки

print("Объём выборки n =", n)
print("Минимум:", np.min(x), "Максимум:", np.max(x))

# === Шаг 1. Разделение на интервалы ===
x_min, x_max = 0.0, np.max(x)
bins = np.linspace(x_min, x_max, num_bins + 1)  # равномерная сетка
print("\nГраницы интервалов (bins):", bins)

# === Шаг 2. Наблюдаемые частоты ===
observed_counts, _ = np.histogram(x, bins)
print("\nНаблюдаемые частоты (Oᵢ):", observed_counts)

# === Шаг 3. Функция распределения экспоненциального распределения ===
def exp_cdf(x, lambda_):
    return 1 - np.exp(-lambda_ * x)

# === Шаг 4. Вычисление ожидаемых частот (Eᵢ) ===
expected_counts = []
interval_probs = []  # вероятности попадания в интервал

print("\nОжидаемые частоты (Eᵢ) по интервалам:")
for i in range(num_bins):
    a, b = bins[i], bins[i + 1]
    p = exp_cdf(b, lambda_) - exp_cdf(a, lambda_)  # вероятность попасть в интервал
    interval_probs.append(p)
    e = n * p  # ожидаемое количество элементов
    expected_counts.append(e)
    print(f"Интервал [{a:.3f}, {b:.3f}): P = {p:.4f}, E = {e:.2f}")

expected_counts = np.array(expected_counts)

# === Шаг 5. Вычисление хи-квадрат статистики ===
chi_squared_stat = np.sum((observed_counts - expected_counts) ** 2 / expected_counts)
print("\nХи-квадрат статистика:", round(chi_squared_stat, 4))

# === Шаг 6. Критическое значение ===
df = num_bins - 1  # степени свободы
chi_critical = chi2.ppf(1 - alpha, df)
print("Критическое значение (chi² crit) при alpha=0.05 и df=9:", round(chi_critical, 4))

# === Шаг 7. Решение: отвергаем или нет гипотезу ===
print("\nРЕЗУЛЬТАТ:")
if chi_squared_stat < chi_critical:
    print("✔ Гипотеза НЕ отвергается — выборка может быть из экспоненциального распределения.")
else:
    print("✘ Гипотеза отвергается — выборка не похожа на экспоненциальную.")
