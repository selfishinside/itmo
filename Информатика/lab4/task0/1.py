# Словарь с результатами команд
results = {
    "Питонята2023": [23, 17, 21],
    "Победители007": [22, 28],
    "Красавчики": [30, 12, 9, 13],
    "МодельерыXXX": [10, 18, 15, 23],
    "Скоростные": [25, 27],
    "Вышивщики!": [19, 20, 21],
    "Весельчаки": [9, 8, 6, 9, 10],
    "Умники": [20, 21, 22],
}

# Ввод минимального балла
min_score = int(input())

# Перебираем команды и их результаты
selected_teams = [
    team
    for team, scores in results.items()
    if sum(scores) > min_score + 10  # Проверяем, превышает ли сумма баллов порог
]

# Выводим результат, если есть подходящие команды
if selected_teams:
    print("\n".join(selected_teams))