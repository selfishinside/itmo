-- 1.
-- Сделать запрос для получения атрибутов из указанных таблиц, применив фильтры по указанным условиям:
-- Таблицы: Н_ОЦЕНКИ, Н_ВЕДОМОСТИ.
-- Вывести атрибуты: Н_ОЦЕНКИ.КОД, Н_ВЕДОМОСТИ.ИД.
-- Фильтры (AND):
-- a) Н_ОЦЕНКИ.КОД < незач.
-- b) Н_ВЕДОМОСТИ.ДАТА > 2010-06-18.
-- c) Н_ВЕДОМОСТИ.ДАТА = 2022-06-08.
-- Вид соединения: RIGHT JOIN.
SELECT Н_ОЦЕНКИ.КОД, Н_ВЕДОМОСТИ.ИД
FROM Н_ВЕДОМОСТИ
RIGHT JOIN Н_ОЦЕНКИ ON Н_ВЕДОМОСТИ.ОЦЕНКА = Н_ОЦЕНКИ.КОД
WHERE Н_ОЦЕНКИ.КОД < 'незач'
AND Н_ВЕДОМОСТИ.ДАТА > '2010-06-18'
AND Н_ВЕДОМОСТИ.ДАТА = '2022-06-08';


-- 2.
-- Сделать запрос для получения атрибутов из указанных таблиц, применив фильтры по указанным условиям:
-- Таблицы: Н_ЛЮДИ, Н_ВЕДОМОСТИ, Н_СЕССИЯ.
-- Вывести атрибуты: Н_ЛЮДИ.ОТЧЕСТВО, Н_ВЕДОМОСТИ.ЧЛВК_ИД, Н_СЕССИЯ.ИД.
-- Фильтры (AND):
-- a) Н_ЛЮДИ.ИМЯ = Владимир.
-- b) Н_ВЕДОМОСТИ.ИД > 1250972.
-- Вид соединения: LEFT JOIN.
SELECT Н_ЛЮДИ.ОТЧЕСТВО, Н_ВЕДОМОСТИ.ЧЛВК_ИД, Н_СЕССИЯ.ИД
FROM Н_ЛЮДИ
LEFT JOIN Н_ВЕДОМОСТИ ON Н_ЛЮДИ.ИД = Н_ВЕДОМОСТИ.ЧЛВК_ИД
LEFT JOIN Н_СЕССИЯ ON Н_ЛЮДИ.ИД = Н_СЕССИЯ.ЧЛВК_ИД
WHERE Н_ЛЮДИ.ИМЯ = 'Владимир'
AND Н_ВЕДОМОСТИ.ИД > 1250972;

-- 3.
-- Вывести число студентов вечерней формы обучения, которые младше 20 лет.
-- Ответ должен содержать только одно число.
SELECT COUNT(*)
FROM Н_ЛЮДИ AS L
JOIN Н_УЧЕНИКИ AS U ON L.ИД = U.ЧЛВК_ИД
JOIN Н_ПЛАНЫ AS P ON U.ПЛАН_ИД = P.ИД
JOIN Н_ФОРМЫ_ОБУЧЕНИЯ AS FO ON P.ФО_ИД = FO.ИД
WHERE FO.НАИМЕНОВАНИЕ = 'Очно-заочная(вечерняя)'
AND AGE(L.ДАТА_РОЖДЕНИЯ) < INTERVAL '20 years';



-- 4.
-- В таблице Н_ГРУППЫ_ПЛАНОВ найти номера планов, по которым обучается (обучалось) более 2 групп на очной форме обучения.
-- Для реализации использовать подзапрос.
SELECT DISTINCT ГП.ПЛАН_ИД, Группы.Количество_групп
FROM Н_ГРУППЫ_ПЛАНОВ ГП
JOIN (
    SELECT ГРУППА, COUNT(*) AS Количество_групп
    FROM Н_ГРУППЫ_ПЛАНОВ ГП
    JOIN Н_ПЛАНЫ П ON ГП.ПЛАН_ИД = П.ИД
    JOIN Н_ФОРМЫ_ОБУЧЕНИЯ ФО ON П.ФО_ИД = ФО.ИД
    WHERE ФО.НАИМЕНОВАНИЕ = 'Очная'
    GROUP BY ГП.ГРУППА
    HAVING COUNT(*) > 2
) Группы ON ГП.ГРУППА = Группы.ГРУППА
ORDER BY Группы.Количество_групп DESC;


-- 5.
-- Выведите таблицу со средними оценками студентов группы 4100 (Номер, ФИО, Ср_оценка), у которых средняя оценка меньше минимальной оценк(е|и) в группе 3100.
WITH min_grade_3100 AS (
    SELECT MIN(CAST(statement.ОЦЕНКА AS int)) AS min_grade
    FROM Н_УЧЕНИКИ students
    JOIN Н_ВЕДОМОСТИ statement ON students.ЧЛВК_ИД = statement.ЧЛВК_ИД
    WHERE students.ГРУППА = '3100'
    AND statement.ОЦЕНКА NOT IN ('зачет', 'незач', 'неявка', 'осв', '99')
  --SELECT MIN(avg_mark) AS min_avg
  --FROM (
      --SELECT AVG(CAST(statement.ОЦЕНКА AS int)) AS avg_mark
      --FROM Н_УЧЕНИКИ students
      --JOIN Н_ВЕДОМОСТИ statement ON students.ЧЛВК_ИД = statement.ЧЛВК_ИД
      --WHERE students.ГРУППА = '3100'
      --AND statement.ОЦЕНКА NOT IN ('зачет', 'незач', 'неявка', 'осв', '99')
      --GROUP BY students.ЧЛВК_ИД
  --) AS group_3100
)
SELECT 
    students.ЧЛВК_ИД AS Номер,
    CONCAT_WS(' ', people.ФАМИЛИЯ, people.ИМЯ, people.ОТЧЕСТВО) AS ФИО,
    AVG(CAST(statement.ОЦЕНКА AS int)) AS Ср_оценка
FROM 
    Н_УЧЕНИКИ students
JOIN 
    Н_ВЕДОМОСТИ statement ON students.ЧЛВК_ИД = statement.ЧЛВК_ИД
JOIN 
    Н_ЛЮДИ people ON students.ЧЛВК_ИД = people.ИД
WHERE 
    students.ГРУППА = '4100'
    AND statement.ОЦЕНКА NOT IN ('зачет', 'незач', 'неявка', 'осв', '99')
GROUP BY 
    students.ЧЛВК_ИД, people.ФАМИЛИЯ, people.ИМЯ, people.ОТЧЕСТВО
HAVING 
    AVG(CAST(statement.ОЦЕНКА AS int)) > (SELECT min_grade FROM min_grade_3100)
ORDER BY Ср_оценка DESC;


