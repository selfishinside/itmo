WITH plan_ids AS (
    SELECT ПЛАНЫ.ИД
    FROM Н_ПЛАНЫ ПЛАНЫ
    JOIN Н_ФОРМЫ_ОБУЧЕНИЯ ФО ON ПЛАНЫ.ФО_ИД = ФО.ИД
